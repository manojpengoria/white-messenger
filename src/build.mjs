/**
 * Static site build: renders every page from src/content through the shared templates.
 * Header and footer are pre-rendered into each page (SEO-friendly) and also written to
 * /partials for the client-side component loader. Usage: npm run pages
 */
import { mkdir, writeFile, readdir, rm, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { site } from './site.config.mjs';
import { layout, canonical } from './lib/layout.mjs';
import { header, footer } from './lib/components.mjs';
import { articles } from './content/articles.mjs';
import { homePage } from './pages/home.mjs';
import { aiHubPage, aiDetailPages } from './pages/ai.mjs';
import { servicesHubPage, serviceDetailPages } from './pages/services.mjs';
import { engagementHubPage, engagementDetailPages } from './pages/engagement.mjs';
import { industriesHubPage, industryDetailPages } from './pages/industries.mjs';
import { solutionsHubPage, solutionDetailPages } from './pages/solutions.mjs';
import { aboutHubPage, approachPageRender, careersPageRender } from './pages/about.mjs';
import { resourcesHubPage, blogPageRender, aiGuidesPageRender, caseStudiesPageRender, articlePages } from './pages/resources.mjs';
import { contactPage, privacyPage, termsPage, sitemapPage, notFoundPage } from './pages/contact.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIRS = ['ai', 'services', 'engagement-models', 'industries', 'solutions', 'about-us', 'resources', 'contact-us'];

const words = (s) => s.split(/\s+/).filter(Boolean).length;
const textOf = (html) => html.replace(/<script[\s\S]*?<\/script>/g, ' ').replace(/<[^>]+>/g, ' ').replace(/&[a-z#0-9]+;/gi, ' ');

// Reading time for articles (≈ 200 words per minute)
for (const a of articles) {
  const flat = [a.intro, a.recommendations, a.conclusion, a.sections.map((s) => [s.heading, s.blocks.map((b) => (typeof b === 'string' ? b : JSON.stringify(b)))])].flat(Infinity).join(' ');
  a.readTime = Math.max(3, Math.ceil(words(flat) / 200));
}

const pages = [
  homePage(),
  aiHubPage(), ...aiDetailPages(),
  servicesHubPage(), ...serviceDetailPages(),
  engagementHubPage(), ...engagementDetailPages(),
  industriesHubPage(), ...industryDetailPages(),
  solutionsHubPage(), ...solutionDetailPages(),
  aboutHubPage(), approachPageRender(), careersPageRender(),
  resourcesHubPage(), blogPageRender(), aiGuidesPageRender(), caseStudiesPageRender(), ...articlePages(),
  contactPage(), privacyPage(), termsPage(), sitemapPage(), notFoundPage(),
];

// Guard against accidental duplicates in metadata
for (const key of ['path', 'title', 'description']) {
  const seen = new Map();
  for (const p of pages) {
    if (seen.has(p[key])) throw new Error(`Duplicate ${key}: "${p[key]}" (${seen.get(p[key])} and ${p.path})`);
    seen.set(p[key], p.path);
  }
}

// Remove previously generated HTML so deleted pages do not linger
for (const dir of OUT_DIRS) await rm(path.join(ROOT, dir), { recursive: true, force: true });
for (const f of await readdir(ROOT)) if (f.endsWith('.html')) await rm(path.join(ROOT, f));

for (const p of pages) {
  const file = path.join(ROOT, p.path);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, layout(p));
}

// Shared component partials for the JS loader ({{ROOT}} is replaced at runtime)
await mkdir(path.join(ROOT, 'partials'), { recursive: true });
await writeFile(path.join(ROOT, 'partials/header.html'), header('{{ROOT}}') + '\n');
await writeFile(path.join(ROOT, 'partials/footer.html'), footer('{{ROOT}}') + '\n');

// sitemap.xml + robots.txt
const indexable = pages.filter((p) => !p.noindex);
const today = new Date().toISOString().slice(0, 10);
await writeFile(path.join(ROOT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by npm run pages. Domain is set by site.url in src/site.config.mjs (CONFIG PLACEHOLDER). -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${indexable.map((p) => `  <url><loc>${canonical(p.path)}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`);
await writeFile(path.join(ROOT, 'robots.txt'), `User-agent: *\nAllow: /\nDisallow: /partials/\n\nSitemap: ${site.url}/sitemap.xml\n`);

// Client-side search index (loaded lazily by components.js; works on file:// too)
const sectionLabel = { home: 'Home', ai: 'AI', services: 'Services', 'engagement-models': 'Engagement Models', industries: 'Industries', solutions: 'Solutions', 'about-us': 'About Us', resources: 'Resources', 'contact-us': 'Contact', '': 'Company' };
const searchIndex = indexable.map((p) => ({ t: p.title.replace(' | White Messenger', ''), u: p.path, d: p.description, s: sectionLabel[p.nav] ?? 'Page' }));
await writeFile(path.join(ROOT, 'assets/js/search-index.js'), `/* Generated by npm run pages. */\nwindow.WM_SEARCH_INDEX = ${JSON.stringify(searchIndex)};\n`);

// Official technology logos for the homepage strip (devicon, MIT licence)
const TECH_LOGOS = { laravel: 'laravel/laravel-original', nodejs: 'nodejs/nodejs-original', react: 'react/react-original', nextjs: 'nextjs/nextjs-original', vuejs: 'vuejs/vuejs-original', python: 'python/python-original', aws: 'amazonwebservices/amazonwebservices-original-wordmark', azure: 'azure/azure-original', kubernetes: 'kubernetes/kubernetes-original', mysql: 'mysql/mysql-original', postgresql: 'postgresql/postgresql-original' };
await mkdir(path.join(ROOT, 'assets/images/tech'), { recursive: true });
for (const [name, src] of Object.entries(TECH_LOGOS)) {
  await copyFile(path.join(ROOT, `node_modules/devicon/icons/${src}.svg`), path.join(ROOT, `assets/images/tech/${name}.svg`));
}

// Fonts (self-hosted)
await mkdir(path.join(ROOT, 'assets/fonts'), { recursive: true });
await copyFile(path.join(ROOT, 'node_modules/@fontsource-variable/plus-jakarta-sans/files/plus-jakarta-sans-latin-wght-normal.woff2'), path.join(ROOT, 'assets/fonts/plus-jakarta-sans-latin-wght-normal.woff2'));

// Page inventory
const rows = pages.map((p) => {
  const main = layout(p).split('<main id="main" tabindex="-1">')[1].split('</main>')[0];
  return { path: p.path, title: p.title, section: sectionLabel[p.nav] ?? '-', words: words(textOf(main)) };
});
let inv = `# Page inventory\n\nGenerated by \`npm run pages\` on ${today}. ${rows.length} HTML pages. Word counts cover the main content area only (excluding shared header and footer).\n\n| # | Page | Section | Title | Main-content words | Status |\n|---|---|---|---|---|---|\n`;
rows.forEach((r, i) => { inv += `| ${i + 1} | \`${r.path}\` | ${r.section} | ${r.title.replace(/\|/g, "\\|")} | ${r.words} | ${r.path === '404.html' ? 'Complete (utility)' : r.path.match(/privacy|terms/) ? 'Complete. Legal draft, needs counsel review' : 'Complete'} |\n`; });
await writeFile(path.join(ROOT, 'PAGE-INVENTORY.md'), inv);

console.log(`Built ${pages.length} pages, partials, sitemap.xml (${indexable.length} URLs), robots.txt, search index and inventory.`);
